CREATE TABLE app_user (
 id VARCHAR(36) PRIMARY KEY, email VARCHAR(200) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE user_session (
 token_hash VARCHAR(64) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id), expires_at BIGINT NOT NULL
);
CREATE TABLE device (
 id VARCHAR(36) PRIMARY KEY, owner_id VARCHAR(36) NOT NULL REFERENCES app_user(id),
 name VARCHAR(80) NOT NULL, role VARCHAR(16) NOT NULL CHECK (role IN ('SECURITY','CLIMATE')),
 token_hash VARCHAR(64) NOT NULL, last_seen BIGINT, viewer_until BIGINT NOT NULL DEFAULT 0,
 packet VARCHAR(36), sampled_at BIGINT, lost_alerts BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE device_command (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, device_id VARCHAR(36) NOT NULL REFERENCES device(id),
 code INTEGER NOT NULL CHECK (code BETWEEN 1 AND 4), status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL, completed_at BIGINT
);
CREATE INDEX command_pending ON device_command(device_id, status, id);
CREATE TABLE alert (
 device_id VARCHAR(36) NOT NULL REFERENCES device(id), event_id VARCHAR(32) NOT NULL,
 kind VARCHAR(16) NOT NULL, occurred_at BIGINT, uptime_ms BIGINT NOT NULL, received_at BIGINT NOT NULL,
 PRIMARY KEY (device_id, event_id)
);
CREATE INDEX alert_history ON alert(device_id, received_at);
